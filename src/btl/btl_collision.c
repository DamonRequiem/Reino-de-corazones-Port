s32 ApplyAttackBox(s32 attack, s32 x, s32 y, s32 z, s16 halfX, s16 halfY, s16 halfZ) {
    const BattleAttackDef* def;
    BtlObj* opponent;
    s32 sumX;
    s32 sumY;
    s32 sumZ;
    s16 hitCount;
    s32 blocked;
    s32 n;
    s32 result;
    s32 enemyResult;

    def = &sBattleAttackDefs[attack];
    hitCount = 0;
    blocked = FALSE;
    gBtlWork->areaUpdated = TRUE;
    gBtlWork->x3 = x;
    gBtlWork->y3 = y;
    gBtlWork->z3 = z;
    gBtlWork->areaHalfX = halfX;
    gBtlWork->areaHalfY = halfY;
    gBtlWork->areaHalfZ = halfZ;

    if (gBtlWork->flags & BTL_FLAG_VS_BATTLE) {
        if (gBtlWork->flags & BTL_FLAG_PLAYER_CARD_ACTION) {
            opponent = gRikuBtlWork->actor;
        } else {
            opponent = gBtlWork->actor;
        }

        if (CanAttackBoxHitBtlObj(opponent, x, y, z, halfX, halfY, halfZ)) {
            result = ResolveAttackHit(opponent, attack);

            if (result == ATTACK_RESULT_HIT) {
                if (def->hitEffect != NULL) {
                    def->hitEffect(opponent->x, opponent->y, opponent->z);
                }
            }

            return result;
        }
    } else if (gBtlWork->flags & BTL_FLAG_PLAYER_CARD_ACTION) {
        opponent = ListPoolFirst(&gBtlWork->pool);
        sumZ = 0;
        sumY = 0;
        sumX = 0;

        while (opponent != NULL) {
            if (!CanAttackBoxHitBtlObj(opponent, x, y, z, halfX, halfY, halfZ)) {
                opponent = ListPoolNext(&opponent->node);
                continue;
            }

            enemyResult = ResolveAttackHit(opponent, attack);

            if (enemyResult == ATTACK_RESULT_HIT) {
                sumX += opponent->x;
                sumY += opponent->y;
                sumZ += opponent->z;
                hitCount++;

                if (def->flags & ATTACK_FLAG_SINGLE_TARGET) {
                    break;
                }
            } else if (enemyResult == ATTACK_RESULT_BLOCKED) {
                blocked = TRUE;
            }

            opponent = ListPoolNext(&opponent->node);
        }

        if (blocked) {
            return ATTACK_RESULT_BLOCKED;
        }

        n = hitCount;

        if (n > 0) {
            if (def->hitEffect != NULL) {
                sumX /= n;
                sumY /= n;
                sumZ /= n;
                def->hitEffect(sumX, sumY, sumZ);
            }

            return ATTACK_RESULT_HIT;
        }
    } else {
        opponent = gBtlWork->actor;

        if (CanAttackBoxHitBtlObj(opponent, x, y, z, halfX, halfY, halfZ)) {
            result = ResolveAttackHit(opponent, attack);

            if (result == ATTACK_RESULT_HIT) {
                if (def->hitEffect != NULL) {
                    def->hitEffect(opponent->x, opponent->y, opponent->z);
                }
            }

            return result;
        }
    }

    return ATTACK_RESULT_NONE;
}

s32 ApplyAttackAt(s32 attack, s32 x, s32 y, s32 z) {
    return ApplyAttackBox(attack, x, y, z, 16, 16, 16);
}

