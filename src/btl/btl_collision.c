void ColliderInit(Collider* collider, u32 type, u16 radius, u16 height) {
    void* pool;
    collider->otherType = COLLIDER_TYPE_NONE;
    collider->colliding = FALSE;
    collider->standFlags = 0;
    collider->flags = 0;
    collider->radius = radius << 8;
    collider->height = height << 8;
    collider->type = type;
    collider->self = collider;
    collider->touchedTypes = 0;
    pool = ColliderGetPool(type);

    switch (type) {
    case COLLIDER_TYPE_SOLID:
    case COLLIDER_TYPE_PLATFORM:
        collider->flags |= COLLIDER_FLAG_IS_PLATFORM;
        break;
    }

    ListNodeInit(&collider->node, pool, collider);
    ListPoolAppend(&collider->node, pool);
}

void ColliderUnregister(Collider* collider) {
    Collider* self = collider->self;

    if (self == collider) {
        ListPoolRemove(&self->node, ColliderGetPool(self->type));
    }
}

